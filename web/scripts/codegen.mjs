// Generates web/lib/generated/template.ts (types) and template.zod.ts (Zod) from schema/template.schema.json (#2).
// Run through `make codegen` at the repo root, which also regenerates the Python models. Never edit the outputs by hand.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import $RefParser from "@apidevtools/json-schema-ref-parser";
import { compile } from "json-schema-to-typescript";
import { jsonSchemaToZod } from "json-schema-to-zod";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const outDir = resolve(root, "web/lib/generated");
const banner = (what) =>
  `// ${what} Generated by \`make codegen\` from schema/template.schema.json. Do not edit: change the schema and regenerate.\n`;

const schema = JSON.parse(readFileSync(resolve(root, "schema/template.schema.json"), "utf8"));

// Objects in the template are open: a newer minor version may add fields, and readers keep them (docs/schema.md).
// JSON Schema allows extra fields unless told otherwise, but json-schema-to-zod strips them, so say so explicitly.
// Objects the schema closes (`additionalProperties: false`, like sound_ref) stay closed.
const openObjects = (node) => {
  if (Array.isArray(node)) node.forEach(openObjects);
  else if (node && typeof node === "object") {
    if (node.type === "object" && !("additionalProperties" in node)) node.additionalProperties = true;
    Object.values(node).forEach(openObjects);
  }
};

mkdirSync(outDir, { recursive: true });

// Types. Open objects get an index signature, matching the schema.
// The root type is named after the schema's title ("Editrace template"); call it Template, like the Python side.
const typed = structuredClone(schema);
typed.title = "Template";
const types = await compile(typed, "Template", { bannerComment: "" });
writeFileSync(resolve(outDir, "template.ts"), banner("TypeScript types.") + "\n" + types);

// Zod. json-schema-to-zod doesn't follow $ref, so inline the $defs first.
const open = structuredClone(schema);
openObjects(open);
const dereferenced = await $RefParser.dereference(open);
const zod = jsonSchemaToZod(dereferenced, { module: "esm", name: "templateSchema", type: true });
writeFileSync(resolve(outDir, "template.zod.ts"), banner("Zod schema.") + zod + "\n");

// Reader variant (#206): the same schema with every `enum` keyword removed, so an unknown enum value from a newer minor
// version doesn't fail the whole template (docs/schema.md). Nothing else is relaxed. Mirrors scripts/reader_schema.py.
const withoutEnums = (node) => {
  if (Array.isArray(node)) return node.map(withoutEnums);
  if (node && typeof node === "object") {
    return Object.fromEntries(
      Object.entries(node)
        .filter(([key, value]) => !(key === "enum" && Array.isArray(value)))
        .map(([key, value]) => [key, withoutEnums(value)]),
    );
  }
  return node;
};
const reader = jsonSchemaToZod(withoutEnums(dereferenced), { module: "esm", name: "templateReaderSchema", type: true });
writeFileSync(resolve(outDir, "template.reader.zod.ts"), banner("Zod schema for readers (enums relaxed to strings).") + reader + "\n");

// What readers need to know about the schema they were built from. SCHEMA_VERSION comes from schema/VERSION, the one
// place the version is written down. KNOWN_TRACK_KINDS comes from the schema's own per-kind rules in the Track
// definition: `kind` is a free string, so an unknown one never fails validation and readers report it as skipped.
const version = readFileSync(resolve(root, "schema/VERSION"), "utf8").trim();
if (!/^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$/.test(version)) {
  throw new Error(`schema/VERSION must hold a semver like 0.1.0, not "${version}"`);
}
const trackKinds = schema.$defs.Track.allOf
  .map((rule) => rule.if?.properties?.kind?.const)
  .filter((kind) => typeof kind === "string");
if (trackKinds.length === 0) throw new Error("found no track kinds in the Track definition's allOf rules; update codegen.mjs");
writeFileSync(
  resolve(outDir, "constants.ts"),
  `// What readers know about the schema these types were generated from. Generated by \`make codegen\` from schema/VERSION and schema/template.schema.json. Do not edit.\n` +
    `export const SCHEMA_VERSION = ${JSON.stringify(version)};\n` +
    `export const KNOWN_TRACK_KINDS: ReadonlySet<string> = new Set(${JSON.stringify(trackKinds)});\n`,
);

console.log("Generated web/lib/generated/template.ts, template.zod.ts, template.reader.zod.ts and constants.ts");
